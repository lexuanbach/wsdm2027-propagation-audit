"""Regenerate the two main-text plots (Fig. 2 forest, Fig. 2 drift/mitigation).

Every plotted number is read from a shipped result JSON and written out as a
plain-text .dat file next to the .tex fragment, so a reader can diff the
figure against the JSON without running anything.

Sources
  Fig. 2   outputs/r11/graph_informative_clustered/{upfd_politifact,
           upfd_gossipcop,twitter15,twitter16,weibo}.json
           fields clustered_best_graph_vs_best_summary / _vs_histgbt
                  -> mean, ci95, p, tost_equivalent_0.03, n_stories
  Fig. 2a  outputs/r10/temporal_drift/summary_v2.json
           <corpus>.drift.per_feature -> ks
  Fig. 2b  outputs/r10/temporal_drift/summary_v2.json
           <corpus>.results[model][arm].per_seed  (5 seeds) -> paired deltas

Run:  cd artifact && PYTHONPATH=src python3 scripts/rev7_make_paper_figures.py
"""
from __future__ import annotations

import json
import math
import os
from pathlib import Path

ART = Path(__file__).resolve().parents[1]
FIG = ART / "generated" / "figures"
DAT = FIG / "data"

# Student-t 97.5% quantile for 4 degrees of freedom (5 seeds, paired).
T975_DF4 = 2.776445105


def load(rel: str):
    return json.loads((ART / rel).read_text())


def write_dat(name: str, header: str, cols: list[str], rows: list[list]) -> Path:
    DAT.mkdir(parents=True, exist_ok=True)
    path = DAT / name
    with path.open("w") as f:
        for line in header.strip().splitlines():
            f.write(f"# {line.strip()}\n")
        f.write(" ".join(cols) + "\n")
        for r in rows:
            f.write(" ".join(str(x) for x in r) + "\n")
    print(f"[dat] {path.relative_to(FIG.parent)}  ({len(rows)} rows)")
    return path


# --------------------------------------------------------------------------
# Figure 2 -- per-corpus forest plot of graph-minus-summary effects
# --------------------------------------------------------------------------
FOREST = [
    # (json stem, y position, printed label)
    ("upfd_politifact", 5, "UPFD-PolitiFact"),
    ("upfd_gossipcop", 4, "UPFD-GossipCop"),
    ("twitter15", 3, "Twitter15"),
    ("twitter16", 2, "Twitter16"),
    ("weibo", 1, "Weibo"),
]
OFFSET = 0.17


def figure2() -> int:
    series = {
        "bs": ("clustered_best_graph_vs_best_summary", +OFFSET),
        "hg": ("clustered_best_graph_vs_histgbt", -OFFSET),
    }
    buckets: dict[str, list[list]] = {k: [] for k in
                                      ("bs_filled", "bs_hollow", "hg_filled", "hg_hollow")}
    audit = []
    n_points = 0
    for stem, y, label in FOREST:
        d = load(f"outputs/r11/graph_informative_clustered/{stem}.json")
        dup = d["best_summary"] == "histgbt"
        for tag, (field, off) in series.items():
            if tag == "hg" and dup:
                # best summary model IS HistGBT here: the two comparisons are
                # literally the same estimate. Draw it once, never twice.
                audit.append(f"{stem}: best_summary==histgbt, vs-HistGBT marker "
                             f"suppressed (duplicate of vs-best-summary)")
                continue
            v = d[field]
            lo, hi = v["ci95"]
            filled = "filled" if v["tost_equivalent_0.03"] else "hollow"
            buckets[f"{tag}_{filled}"].append([
                round(y + off, 3), v["mean"],
                round(v["mean"] - lo, 4), round(hi - v["mean"], 4),
            ])
            audit.append(f"{stem} {field}: mean={v['mean']} ci95={v['ci95']} "
                         f"p={v['p']} tost0.03={v['tost_equivalent_0.03']} "
                         f"n_stories={v['n_stories']}")
            n_points += 1

    src = ("Fig. 2 source: outputs/r11/graph_informative_clustered/<corpus>.json\n"
           "cols: y = row position, mean = clustered paired accuracy gain of the\n"
           "best graph model, eminus/eplus = distance to the clustered 95% CI ends.\n"
           "filled = TOST-equivalent at margin 0.03; hollow = not certified.")
    cols = ["y", "mean", "eminus", "eplus"]
    for key, rows in buckets.items():
        if rows:
            write_dat(f"forest_{key}.dat", src, cols, rows)
    (DAT / "forest_audit.txt").write_text("\n".join(audit) + "\n")

    tex = [r"% AUTO-GENERATED by artifact/scripts/rev7_make_paper_figures.py -- do not edit.",
           r"\begin{tikzpicture}",
           r"\begin{axis}[",
           r"  width=0.74\columnwidth, height=4.1cm, scale only axis,",
           r"  xlabel={$\Delta$ accuracy: selected graph model $-$ comparator},",
           r"  xlabel style={font=\scriptsize, yshift=2pt},",
           r"  xmin=-0.105, xmax=0.135, ymin=0.45, ymax=5.55,",
           r"  xtick={-0.10,-0.05,0,0.05,0.10},",
           r"  xticklabels={$-0.10$,$-0.05$,$0$,$0.05$,$0.10$},",
           r"  xticklabel style={font=\scriptsize},",
           r"  ytick={1,2,3,4,5},",
           r"  yticklabels={Weibo, Twitter16, Twitter15, UPFD-GossipCop, UPFD-PolitiFact},",
           r"  yticklabel style={font=\scriptsize},",
           r"  ymajorgrids, grid style={gray!25},",
           r"  tick align=outside, tick pos=left,",
           r"]",
           r"\fill[black!8] (axis cs:-0.03,0.45) rectangle (axis cs:0.03,5.55);",
           r"\draw[black!55, densely dashed] (axis cs:0,0.45) -- (axis cs:0,5.55);"]
    style = {
        "bs": "mark=*, color=black",
        "bs_hollow": "mark=o, color=black",
        "hg": "mark=square*, color=black!55",
        "hg_hollow": "mark=square, color=black!55",
    }
    for key in ("bs_filled", "bs_hollow", "hg_filled", "hg_hollow"):
        if not buckets[key]:
            continue
        base = key.split("_")[0]
        st = style[base] if key.endswith("filled") else style[base + "_hollow"]
        tex.append(
            r"\addplot[only marks, " + st + r", mark size=1.7pt, line width=0.6pt,"
            "\n  error bars/.cd, x dir=both, x explicit, error bar style={line width=0.6pt}]"
            "\n  table[x=mean, y=y, x error plus=eplus, x error minus=eminus] "
            "{figures/data/forest_" + key + ".dat};")
    tex += [r"\end{axis}", r"\end{tikzpicture}"]
    (FIG / "forest_graphinf.tex").write_text("\n".join(tex) + "\n")
    print(f"[tex] figures/forest_graphinf.tex  ({n_points} plotted intervals)")
    return n_points


# --------------------------------------------------------------------------
# Figure 3(a) -- per-feature KS drift
# --------------------------------------------------------------------------
# log_urls / log_media are KS=0 BY CONSTRUCTION (1 URL and 0 media for every
# cascade in these releases), and log_users is identical to log_n because the
# loader sets user_id = tweet id. Plotting them would be padding, so the figure
# carries the four features that can actually move; the body text says why.
KS_KEEP = [("log_spread", "spread"), ("log_n", "logn"),
           ("echo", "echo"), ("log_pop", "logP")]


def figure3a() -> int:
    d = load("outputs/r10/temporal_drift/summary_v2.json")
    ks = {c: {r["feature"]: r["ks"] for r in d[c]["drift"]["per_feature"]}
          for c in ("politifact", "gossipcop")}
    for c in ("politifact", "gossipcop"):
        assert ks[c]["log_urls"] == 0.0 and ks[c]["log_media"] == 0.0
        assert ks[c]["log_users"] == ks[c]["log_n"]
    rows = [[sym, ks["politifact"][feat], ks["gossipcop"][feat]]
            for feat, sym in reversed(KS_KEEP)]
    write_dat("ks_drift.dat",
              "Fig. 2(a) source: outputs/r10/temporal_drift/summary_v2.json,\n"
              "<corpus>.drift.per_feature[].ks (two-sample KS, train era vs future era).\n"
              "log_urls and log_media are omitted: KS=0 by construction (every cascade\n"
              "has exactly 1 URL and 0 media). log_users is omitted: identical to log_n.",
              ["feature", "politifact", "gossipcop"], rows)
    return len(rows) * 2


# --------------------------------------------------------------------------
# Figure 3(b) -- paired future-test delta of each label-free correction
# --------------------------------------------------------------------------
ARMS = [("testtime", "test-std."), ("quantile", "quantile"),
        ("impweight", "imp.-wt"), ("coral", "CORAL")]
MODELS = [("propmlp", "PropMLP", +0.22), ("propmlp_plus", "PropMLP+", 0.0),
          ("rf", "RForest", -0.22)]


def figure3b() -> int:
    d = load("outputs/r10/temporal_drift/summary_v2.json")
    n_points = 0
    for corpus in ("politifact", "gossipcop"):
        res = d[corpus]["results"]
        for model, _lbl, off in MODELS:
            rows = []
            base = res[model]["baseline"]["per_seed"]
            assert len(base) == 5
            for ai, (arm, _al) in enumerate(ARMS):
                arm_seed = res[model][arm]["per_seed"]
                assert len(arm_seed) == 5
                deltas = [a - b for a, b in zip(arm_seed, base)]
                m = sum(deltas) / len(deltas)
                var = sum((x - m) ** 2 for x in deltas) / (len(deltas) - 1)
                half = T975_DF4 * math.sqrt(var / len(deltas))
                y = len(ARMS) - ai  # top row = first arm
                rows.append([round(y + off, 3), round(m, 4), round(half, 4)])
                n_points += 1
            write_dat(f"mitig_{corpus}_{model}.dat",
                      f"Fig. 2(b) source: outputs/r10/temporal_drift/summary_v2.json,\n"
                      f"{corpus}.results.{model}.<arm>.per_seed minus .baseline.per_seed\n"
                      "(5 paired seeds). err = half-width of the seed-level 95% CI\n"
                      "(t_{0.975,4} * sd/sqrt(5)). Rows top-to-bottom: "
                      + ", ".join(a for a, _ in ARMS) + ".",
                      ["y", "delta", "err"], rows)

    # Template: the restyled figure is kept verbatim in
    # DRIFT_TEX (muted palette, plain-language labels); only the data files
    # above are regenerated from the JSON.
    tex = DRIFT_TEX
    (FIG / "drift_mitig.tex").write_text(tex)
    print(f"[tex] figures/drift_mitig.tex  ({n_points} plotted deltas + KS panel)")
    return n_points


