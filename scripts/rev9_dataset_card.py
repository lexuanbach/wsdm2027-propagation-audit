"""SHA-256 checksum card for every released input the audit reads.

Required-checklist item 7 asks for dataset checksums alongside the split IDs.
This walks artifact/data/raw and external/, hashes each file the loaders open,
and records size and mtime.  Derived caches that the pipeline regenerates
(*graph/ directories built by the BiGCN preprocessor, PyG `processed/` folders)
are listed by name and count but not hashed, because they are outputs, not
released inputs.

Licences are deliberately NOT asserted: the supplement's dataset card states
terms only where they are recoverable from the released files themselves, and
this card keeps that rule.

Usage: PYTHONPATH=src python3 scripts/rev9_dataset_card.py
"""
from __future__ import annotations

import hashlib
import json
import pathlib
import time

ROOT = pathlib.Path(__file__).resolve().parents[1]
EXT = ROOT / "external"
OUT = ROOT / "outputs" / "r15" / "dataset_card"

# directories whose contents are regenerated by the pipeline, not released inputs
DERIVED = ("graph", "processed")
MAX_HASH_BYTES = 400 * 1024 * 1024      # skip hashing anything larger; record size only


def sha256(p: pathlib.Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def is_derived(p: pathlib.Path, base: pathlib.Path) -> bool:
    return any(part.endswith(DERIVED) or part in DERIVED
               for part in p.relative_to(base).parts[:-1])


def walk(base: pathlib.Path, label: str) -> dict:
    files, derived, total = {}, 0, 0
    if not base.exists():
        return {"root": label, "present": False}
    for p in sorted(base.rglob("*")):
        if not p.is_file() or p.name == ".DS_Store":
            continue
        rel = str(p.relative_to(base))
        size = p.stat().st_size
        total += size
        if is_derived(p, base):
            derived += 1
            continue
        rec = {"bytes": size, "mtime": time.strftime("%Y-%m-%d", time.gmtime(p.stat().st_mtime))}
        rec["sha256"] = sha256(p) if size <= MAX_HASH_BYTES else "not-hashed:over-400MB"
        files[rel] = rec
    return {"root": label, "present": True, "n_hashed": len(files),
            "n_derived_skipped": derived, "total_bytes": total, "files": files}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    card = {
        "generated": time.strftime("%Y-%m-%d"),
        "scope": ("released inputs actually opened by the loaders; regenerated caches "
                  "(*graph/, processed/) are counted, not hashed"),
        "licence_policy": ("no licence is named here unless it is recoverable from the "
                           "released files; see the supplement dataset card"),
        "trees": [walk(ROOT / "data" / "raw", "artifact/data/raw"),
                  walk(EXT / "BiGCN" / "data", "external/BiGCN/data"),
                  walk(EXT / "upfd", "external/upfd")],
    }
    (OUT / "dataset_card.json").write_text(json.dumps(card, indent=2))
    for t in card["trees"]:
        if t.get("present"):
            print(f"{t['root']:26s} hashed={t['n_hashed']:5d} derived_skipped={t['n_derived_skipped']:6d} "
                  f"total={t['total_bytes']/1e6:.1f} MB")
        else:
            print(f"{t['root']:26s} MISSING")


if __name__ == "__main__":
    main()
