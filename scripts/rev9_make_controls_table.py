"""Emit the graph-input controls table (main text) from the run files.

Columns: intact BiGCN-style mean, degree-preserving rewire delta, and
global profile-permutation delta.  Every number is read from the recorded
outputs; nothing is transcribed by hand.  Corpora with no released profile
vectors print an em dash in the permutation column, which is a real property of
those releases rather than a missing run.
"""
from __future__ import annotations

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
REWIRE = ROOT / "outputs" / "r13" / "edge_rewire" / "analysis.json"
PERM = ROOT / "outputs" / "r15" / "profile_permute" / "analysis.json"
OUT = ROOT / "generated" / "tables" / "controls_table.tex"

ORDER = [("upfd_gossipcop", "UPFD-GossipCop"), ("upfd_politifact", "UPFD-PolitiFact"),
         ("twitter15", "Twitter15"), ("twitter16", "Twitter16")]


def star(p):
    return "^{*}" if p is not None and p < 0.05 else ""


def main():
    rw = json.loads(REWIRE.read_text())["per_corpus"]
    pm = json.loads(PERM.read_text())["per_variant"].get("global", {})
    rows = []
    for key, pretty in ORDER:
        r = rw[key]
        intact = r["bigcn_intact_mean"]
        d_rw = r["seed_paired_rewired_vs_intact"]["mean_delta"]
        p_rw = r["seed_paired_rewired_vs_intact"]["p"]
        if key in pm:
            c = pm[key]["bigcn"]
            perm = f"${c['delta']:+.4f}{star(c['p_seed_paired'])}$"
        elif key.startswith("upfd_"):
            # a UPFD corpus HAS profile vectors, so a missing cell means a
            # missing run -- never print it as if the release lacked the signal
            raise SystemExit(f"no global profile-permutation result for {key}; "
                             "run scripts/rev9_profile_permute.py --variant global")
        else:
            perm = "n/a"          # no released profile vectors on this corpus
        rows.append(f"{pretty:15s} & ${intact:.4f}$ & ${d_rw:+.4f}{star(p_rw)}$ & {perm} \\\\")
    body = "\n".join(rows)
    tex = ("% AUTO-GENERATED by artifact/scripts/rev9_make_controls_table.py "
           "-- do not edit.\n"
           "\\begin{tabular}{lccc}\n\\toprule\n"
           "\\tabhead \\textbf{Corpus} & \\textbf{intact graph} & \\textbf{rewired edges} $\\Delta$ "
           "& \\textbf{shuffled profiles} $\\Delta$ \\\\\n\\midrule\n"
           f"{body}\n\\bottomrule\n\\end{{tabular}}\n")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(tex)
    print(tex)


if __name__ == "__main__":
    main()
